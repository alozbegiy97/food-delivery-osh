"""Declarative base and shared column mixins for ORM models.

Conventions (DATABASE_SCHEMA.md §2.1, DEC-63):
- primary keys are UUIDs generated by PostgreSQL (`gen_random_uuid()`);
- `created_at` / `updated_at` are `TIMESTAMPTZ` with `DEFAULT now()`;
- `updated_at` is refreshed by SQLAlchemy on every ORM update (`onupdate`).

The naming convention keeps constraint names stable for Alembic migrations.
Tables are created only by Alembic migrations, never by `create_all()`.
"""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, MetaData, func, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


# `sort_order` keeps a readable column order in tables: id first,
# timestamps last.


class UUIDPrimaryKeyMixin:
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=text("gen_random_uuid()"),
        sort_order=-100,
    )


class CreatedAtMixin:
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(), sort_order=100
    )


class TimestampMixin(CreatedAtMixin):
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
        sort_order=101,
    )
